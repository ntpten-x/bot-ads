export function canonicalHeader(header: string) {
  const key = header
    .replace(/^\uFEFF/, "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
  const withoutCurrency = key.replace(/\s*\([a-z]{3}\)$/, "");
  return (
    reportAliases[key] ??
    reportAliases[withoutCurrency] ??
    key.replaceAll(" ", "_")
  );
}
